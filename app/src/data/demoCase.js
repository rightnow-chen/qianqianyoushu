/** 取全文，用于「识别全文」模式与导出 */
export function getContractText(pages = DEMO_PAGES) {
  return pages
    .map((page) =>
      page.blocks
        .map((block) => {
          if (block.runs) return block.runs.map((run) => run.t).join('')
          if (block.type === 'party') return `${block.text}　${block.mask || ''}`.trim()
          return block.text
        })
        .filter(Boolean)
        .join('\n'),
    )
    .join('\n\n')
}
