/** 把模板里的变量位替换掉；缺的变量直接省略，不留「{}」。 */
function fill(text, vars) {
  return text.replace(/\{(\w+)\}/g, (_, key) => {
    const value = vars[key]
    return value === undefined || value === null || value === '' ? '' : String(value)
  })
}

export function scriptFor(cat, vars = {}) {
  const tpl = cat === '违约金' ? BREACH : T[cat] || FALLBACK
  const safe = {
    loc: vars.article ? `第${vars.article}条` : '合同',
    amount: vars.amountText && vars.amountText !== '—' ? vars.amountText : '这笔费用',
    ask: vars.ask || '能不能把标准写清楚',
  }
  return {
    polite: fill(tpl.polite, safe),
    firm: fill(tpl.firm, safe),
    objections: tpl.objections.map((item) => ({ q: item.q, a: fill(item.a, safe) })),
  }
}

